interface LocaleContextValue {
  locale: UiLocale;
  isEnglish: boolean;
  t: (message: string, values?: Record<string, string | number>) => string;
  setLocale: (locale: UiLocale) => Promise<void>;
}

const LocaleContext = createContext<LocaleContextValue | null>(null);

function storedLocale(): UiLocale {
  const value = window.localStorage.getItem(STORAGE_KEY);
  if (value === "zh-CN" || value === "en-US") return value;
  return window.navigator.language.toLowerCase().startsWith("en")
    ? "en-US"
    : "zh-CN";
}

function interpolate(
  value: string,
  values: Record<string, string | number> | undefined,
) {
  if (!values) return value;
  return Object.entries(values).reduce(
    (result, [key, replacement]) =>
      result.replaceAll(`{${key}}`, String(replacement)),
    value,
  );
}

export function LocaleProvider({ children }: { children: ReactNode }) {
  const { profile, status, reloadProfile } = useCoreAuth();
  const [locale, setLocaleState] = useState<UiLocale>(storedLocale);

  useEffect(() => {
    const serverLocale = profile?.user.locale;
    if (!serverLocale) return;
    setLocaleState(serverLocale);
    window.localStorage.setItem(STORAGE_KEY, serverLocale);
  }, [profile?.user.id, profile?.user.locale]);

  useEffect(() => {
    document.documentElement.lang = locale;
  }, [locale]);

  const setLocale = useCallback(
    async (nextLocale: UiLocale) => {
      if (nextLocale === locale) return;
      const previous = locale;
      setLocaleState(nextLocale);
      window.localStorage.setItem(STORAGE_KEY, nextLocale);
      try {
        if (status === "authenticated") {
          await updateUserPreferences(nextLocale);
          await reloadProfile();
        }
      } catch (error) {
        setLocaleState(previous);
        window.localStorage.setItem(STORAGE_KEY, previous);
        throw error;
      }
    },
    [locale, reloadProfile, status],
  );

  const value = useMemo<LocaleContextValue>(
    () => ({
      locale,
      isEnglish: locale === "en-US",
      t: (message, values) =>
        interpolate(locale === "en-US" ? english[message] ?? message : message, values),
      setLocale,
    }),
    [locale, setLocale],
  );

  return (
    <LocaleContext.Provider value={value}>{children}</LocaleContext.Provider>
  );
}

export function useLocale() {
  const value = useContext(LocaleContext);
  if (!value) throw new Error("useLocale must be used within LocaleProvider");
  return value;
}
