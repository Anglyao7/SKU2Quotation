"""Repair exact repeated SKU specification suffixes without retranslation.

The command is dry-run by default. Applying requires the tenant UUID to be
repeated through ``--confirm-tenant-id``. Only the exact suffix generated by
the Product + SKU workbook importer is removed; fuzzy name rewriting is never
performed.
"""

from __future__ import annotations

import argparse
import json
from dataclasses import dataclass
from uuid import UUID

from sqlalchemy import select

from app import db_models as _db_models  # noqa: F401
from app.catalog_translation_models import (
    CatalogLanguagePackRow,
    CatalogSkuTranslationRow,
    CatalogTranslationOverrideRow,
)
from app.database import SessionLocal, set_request_context
from app.model_mixins import utcnow
from app.product_center_models import SkuRow
from app.repositories import public_catalog_repository
from app.services.catalog_translation import catalog_translation_source
from app.services.product_template_import import _sku_name_with_specification


ZERO_UUID = UUID(int=0)


@dataclass(frozen=True, slots=True)
class NameRepair:
    sku_id: UUID
    specification: str
    before: str
    after: str
    repetition_count: int


def _sku_specification(sku: SkuRow) -> str | None:
    values = sku.option_values if isinstance(sku.option_values, dict) else {}
    value = values.get("规格名称") or values.get("specification")
    normalized = str(value or "").strip()
    return normalized or None


def _exact_suffix_repetition_count(name: str, specification: str) -> int:
    suffix = f" · {specification.strip()}"
    remaining = name.strip()
    count = 0
    while suffix.strip() and remaining.endswith(suffix):
        remaining = remaining[: -len(suffix)].rstrip()
        count += 1
    return count


def _collapse_translated_repetition(
    name: str,
    *,
    maximum_removals: int,
) -> str:
    """Collapse only identical adjacent translated suffix segments."""

    parts = [part.strip() for part in name.split(" · ")]
    removals = 0
    while (
        removals < maximum_removals
        and len(parts) >= 3
        and parts[-1].casefold() == parts[-2].casefold()
    ):
        parts.pop()
        removals += 1
    return " · ".join(parts)


def _candidate_repairs(skus: list[SkuRow]) -> list[NameRepair]:
    repairs: list[NameRepair] = []
    for sku in skus:
        name = str(sku.name or "").strip()
        specification = _sku_specification(sku)
        if not name or not specification:
            continue
        repetition_count = _exact_suffix_repetition_count(name, specification)
        if repetition_count < 2:
            continue
        normalized = _sku_name_with_specification(name, specification)
        if normalized == name:
            continue
        repairs.append(
            NameRepair(
                sku_id=sku.id,
                specification=specification,
                before=name,
                after=normalized,
                repetition_count=repetition_count,
            )
        )
    return repairs


def _parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--tenant-id", required=True, type=UUID)
    parser.add_argument("--apply", action="store_true")
    parser.add_argument("--confirm-tenant-id", type=UUID)
    parser.add_argument("--examples", type=int, default=10)
    return parser


def main() -> None:
    args = _parser().parse_args()
    tenant_id: UUID = args.tenant_id
    if args.apply and args.confirm_tenant_id != tenant_id:
        raise SystemExit(
            "--apply requires --confirm-tenant-id to exactly match --tenant-id"
        )

    with SessionLocal() as session:
        set_request_context(
            session,
            organization_id=ZERO_UUID,
            tenant_id=tenant_id,
            user_id=ZERO_UUID,
        )
        skus = list(
            session.scalars(
                select(SkuRow).where(
                    SkuRow.tenant_id == tenant_id,
                    SkuRow.deleted_at.is_(None),
                )
            ).all()
        )
        repairs = _candidate_repairs(skus)
        result: dict[str, object] = {
            "mode": "apply" if args.apply else "dry-run",
            "tenant_id": str(tenant_id),
            "scanned_skus": len(skus),
            "repairable_skus": len(repairs),
            "examples": [
                {
                    "sku_id": str(repair.sku_id),
                    "before": repair.before,
                    "after": repair.after,
                    "repetition_count": repair.repetition_count,
                }
                for repair in repairs[: max(0, args.examples)]
            ],
        }
        if not args.apply or not repairs:
            session.rollback()
            print(json.dumps(result, ensure_ascii=False, indent=2))
            return

        repairs_by_id = {repair.sku_id: repair for repair in repairs}
        skus_by_id = {sku.id: sku for sku in skus}
        for repair in repairs:
            sku = skus_by_id[repair.sku_id]
            sku.name = repair.after
            sku.version += 1
        session.flush()

        public_rows = public_catalog_repository.list_all_public_catalog_rows(
            session,
            tenant_id=tenant_id,
            now=utcnow(),
        )
        sources_by_sku_id = {
            source.sku_id: source
            for source in map(catalog_translation_source, public_rows)
            if source.sku_id in repairs_by_id
        }
        translations = list(
            session.scalars(
                select(CatalogSkuTranslationRow).where(
                    CatalogSkuTranslationRow.tenant_id == tenant_id,
                    CatalogSkuTranslationRow.sku_id.in_(repairs_by_id),
                )
            ).all()
        )
        preserved_translations = 0
        stale_private_translations = 0
        normalized_translated_names = 0
        for translation in translations:
            repair = repairs_by_id[translation.sku_id]
            normalized_translation_name = _collapse_translated_repetition(
                translation.name,
                maximum_removals=repair.repetition_count - 1,
            )
            if normalized_translation_name != translation.name:
                translation.name = normalized_translation_name
                normalized_translated_names += 1
            source = sources_by_sku_id.get(translation.sku_id)
            if source is None:
                # A non-public SKU cannot be safely re-hashed from the public
                # content contract. Leave it stale so a later publish performs
                # the normal incremental translation check.
                stale_private_translations += 1
                continue
            translation.source_hash = source.source_hash
            translation.product_version = source.product_version
            translation.sku_version = source.sku_version
            preserved_translations += 1

        overrides = list(
            session.scalars(
                select(CatalogTranslationOverrideRow).where(
                    CatalogTranslationOverrideRow.tenant_id == tenant_id,
                    CatalogTranslationOverrideRow.entity_type == "SKU",
                    CatalogTranslationOverrideRow.entity_id.in_(repairs_by_id),
                )
            ).all()
        )
        preserved_overrides = 0
        for override in overrides:
            source = sources_by_sku_id.get(override.entity_id)
            if source is None:
                continue
            values = dict(override.values or {})
            translated_name = values.get("name")
            if isinstance(translated_name, str):
                repair = repairs_by_id[override.entity_id]
                values["name"] = _collapse_translated_repetition(
                    translated_name,
                    maximum_removals=repair.repetition_count - 1,
                )
                override.values = values
            override.source_hash = source.source_hash
            preserved_overrides += 1

        language_pack_count = len(
            session.scalars(
                select(CatalogLanguagePackRow.id).where(
                    CatalogLanguagePackRow.tenant_id == tenant_id,
                    CatalogLanguagePackRow.deleted_at.is_(None),
                )
            ).all()
        )
        session.commit()
        result.update(
            {
                "updated_skus": len(repairs),
                "preserved_translation_rows": preserved_translations,
                "stale_non_public_translation_rows": stale_private_translations,
                "normalized_translated_names": normalized_translated_names,
                "preserved_manual_overrides": preserved_overrides,
                "language_packs_requiring_republish": language_pack_count,
            }
        )
        print(json.dumps(result, ensure_ascii=False, indent=2))


if __name__ == "__main__":
    main()
